def human_sheet(rows, animated):
    down=pixels(rows,SP); back=down.copy(); d=ImageDraw.Draw(back)
    d.rectangle((5,4,10,7),fill=SP[2]);d.rectangle((5,9,10,12),fill=SP[1]);d.rectangle((6,10,9,11),fill=SP[2])
    side=down.copy();d=ImageDraw.Draw(side);d.rectangle((4,4,6,7),fill=SP[2]);d.point((10,5),fill=SP[1])
    frames=[]
    for base in [down,back,side]:
        frames.append(base)
        if animated:
            step=base.copy();d=ImageDraw.Draw(step);d.rectangle((4,14,6,15),fill=SP[0]);d.rectangle((5,14,7,15),fill=SP[1]);frames.append(step)
    sheet=Image.new('RGB',(16*len(frames),16),SP[0])
    for i,f in enumerate(frames):sheet.paste(f,(16*i,0))
    return sheet

