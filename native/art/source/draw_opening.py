def pixels(rows, colors):
    im = Image.new('RGB', (len(rows[0]), len(rows)))
    for y, row in enumerate(rows):
        for x, c in enumerate(row): im.putpixel((x,y), tuple(bytes.fromhex(colors[int(c)][1:])))
    return im

